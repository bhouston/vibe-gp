// Work out what each circuit's menu card shows and write src/tracks/cards.js, so the menu
// doesn't build every circuit's full path at startup (seconds of frozen page on a phone).
// Run it after adding or changing a track:
//
//   pnpm cards
import { writeFileSync } from 'node:fs';
import { TRACKS } from '../src/tracks/index.js';
import { TrackPath } from '../src/trackPath.js';

const POINTS = 300; // plenty for an outline about 100 px across

const cards = {};
for (const def of TRACKS) {
  const path = new TrackPath(def);
  const b = path.bounds();
  const size = Math.max(b.maxX - b.minX, b.maxZ - b.minZ);
  const pad = size * 0.08;
  const start = path.poseAt(0);
  const r = (v) => +v.toFixed(1);
  cards[def.id] = {
    viewBox: [b.minX - pad, b.minZ - pad, b.maxX - b.minX + pad * 2, b.maxZ - b.minZ + pad * 2].map(r).join(' '),
    d: path.svgPath(Math.max(1, Math.ceil(path.N / POINTS))),
    stroke: r(size / 45),
    start: [r(start.x), r(start.z)],
    km: (path.length / 1000).toFixed(3),
    elevation: path.elevationRange >= 1 ? Math.round(path.elevationRange) : 0,
  };
}
writeFileSync(new URL('../src/tracks/cards.js', import.meta.url), `// Generated by scripts/track-cards.mjs (pnpm cards): don't edit by hand.\nexport const CARDS = ${JSON.stringify(cards, null, 1)};\n`);
console.log(`${TRACKS.length} track cards written`);
